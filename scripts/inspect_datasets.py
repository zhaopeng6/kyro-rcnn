#!/usr/bin/env python3
"""Inspect the locally configured LabelMe and Pascal VOC datasets without mutation."""
from __future__ import annotations

import argparse
import json
import sys
from collections import Counter
from pathlib import Path

import numpy as np
import yaml

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "chromosome_segmentation"))
from src.datasets.annotations import parse_labelme_annotation, parse_voc_annotation


def percentile_summary(values):
    if not values:
        return {"count": 0}
    a = np.asarray(values, dtype=float)
    return {"count": len(values), "min": float(a.min()), "p50": float(np.percentile(a, 50)),
            "p95": float(np.percentile(a, 95)), "max": float(a.max()), "mean": float(a.mean())}


def overlaps(boxes):
    result = 0
    for i, a in enumerate(boxes):
        for b in boxes[i + 1:]:
            if min(a[2], b[2]) > max(a[0], b[0]) and min(a[3], b[3]) > max(a[1], b[1]): result += 1
    return result


def inspect(paths, parser, patient_from_path):
    dimensions, widths, heights, ratios, bw, bh, labels = [], [], [], [], [], [], Counter()
    images_with_overlap = invalid = annotations = 0
    patients = Counter()
    for path in paths:
        try: ann = parser(path)
        except Exception as exc:
            invalid += 1
            continue
        width, height = ann["width"], ann["height"]
        widths.append(width); heights.append(height); ratios.append(width / height if height else 0)
        dimensions.append([width, height]); invalid += len(ann["invalid"]); annotations += len(ann["instances"])
        patient = patient_from_path(path); patients[patient] += 1
        boxes = []
        for instance in ann["instances"]:
            x1, y1, x2, y2 = instance["box"]; boxes.append(instance["box"])
            bw.append(x2 - x1); bh.append(y2 - y1); labels[instance["label"]] += 1
        images_with_overlap += overlaps(boxes) > 0
    return {"images": len(paths), "annotations": annotations, "invalid_or_missing_annotations": invalid,
            "image_width": percentile_summary(widths), "image_height": percentile_summary(heights),
            "image_aspect_ratio": percentile_summary(ratios), "box_width": percentile_summary(bw),
            "box_height": percentile_summary(bh), "class_label_frequencies": dict(sorted(labels.items())),
            "images_with_overlapping_boxes": images_with_overlap, "patient_identifier_candidates": dict(patients),
            "patient_identifier_note": "AutoKary parent directory is treated as a candidate only; Lowq filename stems are not validated patient IDs."}


def markdown(report):
    lines = ["# Dataset inspection report", "", "Generated by `scripts/inspect_datasets.py`. Pixel dimensions/areas are uncalibrated.", ""]
    for name, data in report["datasets"].items():
        lines += [f"## {name}", "", f"- Images: {data['images']}", f"- Instances: {data['annotations']}",
                  f"- Invalid/missing annotations: {data['invalid_or_missing_annotations']}",
                  f"- Images with overlapping bounding boxes: {data['images_with_overlapping_boxes']}",
                  f"- Width p50/p95: {data['image_width'].get('p50', 'n/a')}/{data['image_width'].get('p95', 'n/a')}",
                  f"- Height p50/p95: {data['image_height'].get('p50', 'n/a')}/{data['image_height'].get('p95', 'n/a')}", ""]
    lines += ["## Annotation findings", "", "- AutoKary is LabelMe polygon annotation; each `shape` is retained as a separate instance.", "- Lowq is Pascal VOC XML box annotation. Its boxes are detection supervision only; no masks are fabricated.", "- Bounding-box intersection is reported separately from true mask overlap.", ""]
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser(); ap.add_argument("--config", default="configs/experiment_a.yaml")
    ap.add_argument("--output-dir", default="outputs/inspection"); args = ap.parse_args()
    config = yaml.safe_load(Path(args.config).read_text()); datasets = config["datasets"]
    autokary_root = Path(datasets["autokary"]["root"])
    lowq = datasets["lowq"]
    report = {"datasets": {
        "autokary": inspect(sorted(autokary_root.rglob("*.json")), lambda p: parse_labelme_annotation(p, rasterize_masks=False), lambda p: p.parent.name),
        "lowq_24_class": inspect(sorted(Path(lowq["annotations"]).glob("*.xml")), parse_voc_annotation, lambda p: p.stem),
    }}
    out = Path(args.output_dir); out.mkdir(parents=True, exist_ok=True)
    (out / "dataset_report.json").write_text(json.dumps(report, indent=2) + "\n")
    (out / "dataset_report.md").write_text(markdown(report))
    print(f"Wrote {out / 'dataset_report.json'} and {out / 'dataset_report.md'}")


if __name__ == "__main__": main()
